class UserModel {
  final String id;
  final String fullName;
  final String email;
  final String phone;
  final String photoUrl;
  final String dateOfBirth;
  final String address;

  UserModel({
    required this.id,
    required this.fullName,
    required this.email,
    required this.phone,
    required this.photoUrl,
    required this.dateOfBirth,
    required this.address,
  });
}
